const fs = require('fs');
const {execFileSync} = require('child_process');
const {request} = require('C:/Users/apexinventives/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const php = 'C:/xampp/php/php.exe';
const fixtureScript = 'tmp/permissions-fixture.php';
const fixture = mode => execFileSync(php, [fixtureScript, mode], {encoding:'utf8'});
const assert = (value, message) => { if (!value) throw new Error(message); };
(async () => {
 fixture('setup');
 const data = JSON.parse(fs.readFileSync('tmp/permissions-fixture.json','utf8'));
 const baseURL = 'http://localhost/Brightvision-Admin/';
 const admin = await request.newContext({baseURL});
 const staff = await request.newContext({baseURL});
 try {
  const login = await admin.post('login.php',{form:{username:data.username,password:data.password}});
  assert(login.ok(),'Admin login failed');
  let page = await admin.get('accounts.php');
  assert(page.status()===200,'Admin accounts denied');
  const html = await page.text();
  const csrf = html.match(/name="csrf_token" value="([a-f0-9]+)"/)[1];
  const staffForm = {csrf_token:csrf,action:'create',full_name:'Permission test staff',username:data.prefix+'_staff',email:data.prefix+'_staff@example.invalid',password:data.password,role:'staff',is_active:'1','permissions[students]':'view','permissions[reservations]':'none','permissions[growth]':'view','permissions[dashboard]':'view'};
  page = await admin.post('accounts.php',{form:staffForm});
  assert((await page.text()).includes('Account and permissions saved'),'Staff creation failed');
  await staff.post('login.php',{form:{username:staffForm.username,password:data.password}});
  page = await staff.get('users.php');
  assert(page.status()===200,'Staff students view denied');
  const studentHtml=await page.text();
  assert(!studentHtml.includes('href="payments.php"') && !studentHtml.includes('href="accounts.php"') && !studentHtml.includes('href="add-user.php"') && !studentHtml.includes('title="Delete"'),'Restricted navigation/actions visible');
  for(const route of ['payments.php','payment-reports.php','payment-reports.php?format=csv','payment-reports.php?format=pdf','accounts.php','settings.php','activity-log.php','reservations.php','add-user.php','edit-user.php?id=0','delete-user.php?id=0','delete-reservation.php?id=0','approve-reservation.php?id=0']) assert((await staff.get(route)).status()===403,'Staff access allowed: '+route);
  for(const route of ['payments.php','accounts.php','bv-growth-upload.php','reservations.php','update-approval.php','save-sms-log.php']) assert((await staff.post(route,{form:{action:'create'}})).status()===403,'Staff mutation allowed: '+route);
  page = await staff.get('index.php');
  assert((await page.text()).includes('Use the navigation menu'),'Dashboard leaked restricted data');
  for(const route of ['payments.php','payment-reports.php']) assert((await admin.get(route)).status()===200,'Admin denied: '+route);
  let accountsHTML=await (await admin.get('accounts.php')).text();
  const accountIds=[...accountsHTML.matchAll(/<dialog id="account-edit-(\d+)"/g)].map(x=>Number(x[1]));
  const staffId=Math.max(...accountIds.filter(id=>id!==data.id));
  // Locate the staff ID by the edit form's username rather than relying on creation order.
  const staffDialog=accountsHTML.split('<dialog ').find(part=>part.includes(`value="${staffForm.username}"`));
  const actualStaffId=Number(staffDialog.match(/id="account-edit-(\d+)"/)[1]);
  page=await admin.post('accounts.php',{form:{...staffForm,action:'update',account_id:String(actualStaffId),password:'','permissions[students]':'manage'}});
  assert((await page.text()).includes('Account and permissions saved'),'Account update failed');
  assert((await staff.get('add-user.php')).status()===200,'Manage permission did not apply to existing session');
  assert((await staff.get('payments.php')).status()===403,'Staff gained payment access');
  page=await admin.post('accounts.php',{form:{...staffForm,action:'update',account_id:String(actualStaffId),csrf_token:'invalid'}});
  assert((await page.text()).includes('Your session expired'),'CSRF rejection missing');
  page=await admin.post('accounts.php',{form:{csrf_token:csrf,action:'delete',account_id:String(data.id)}});
  assert((await page.text()).includes('You cannot delete'),'Own account deletion allowed');
  fixture('revoke');
  assert((await staff.get('users.php')).status()===403,'Revocation did not apply');
  fixture('deactivate');
  page=await staff.get('profile.php',{maxRedirects:0});
  assert(page.status()===302 && page.headers().location==='login.php','Inactive session retained access');
  const crud={...staffForm,username:data.prefix+'_crud',email:data.prefix+'_crud@example.invalid'};
  page=await admin.post('accounts.php',{form:crud});
  const crudDialog=(await page.text()).split('<dialog ').find(part=>part.includes(`value="${crud.username}"`));
  assert(crudDialog,'CRUD test account missing');
  const crudId=crudDialog.match(/id="account-edit-(\d+)"/)[1];
  page=await admin.post('accounts.php',{form:{csrf_token:csrf,action:'delete',account_id:crudId}});
  assert((await page.text()).includes('Account deleted.') && !(await page.text()).includes(`value="${crud.username}"`),'Account deletion failed');
  console.log('Passed: account CRUD, CSRF, admin payment access, staff route/export/mutation restrictions, hidden controls, permission revocation, deactivation and self-deletion protection.');
 } finally {await admin.dispose();await staff.dispose();fixture('cleanup');}
})().catch(error=>{console.error(error.message);process.exit(1)});
